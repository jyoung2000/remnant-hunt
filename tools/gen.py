#!/usr/bin/env python3
"""Generate src/core/gen/sheets.gen.h from the design sheets: one struct per sheet, one row = one entry.

Runs preflight first and refuses to generate if any cell is unfilled, broken or invalid.
usage: gen.py [sheets dir] [out header]
"""
import json, os, re, subprocess, sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, ".."))


def cstr(s):
    return '"' + str(s).replace("\\", "\\\\").replace('"', '\\"') + '"'


def ident(s):
    return re.sub(r"[^A-Za-z0-9]", "_", str(s)).upper()


def main():
    d = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, "sheets")
    out = sys.argv[2] if len(sys.argv) > 2 else os.path.join(ROOT, "src", "core", "gen", "sheets.gen.h")
    r = subprocess.run([sys.executable, os.path.join(HERE, "preflight.py"), d], capture_output=True, text=True)
    if r.returncode != 0:
        print(r.stdout)
        sys.exit("preflight failed: fix the sheets first")
    sheets = {}
    for n in sorted(os.listdir(d)):
        if n.endswith(".json") and not n.startswith("_"):
            sh = json.load(open(os.path.join(d, n), encoding="utf-8"))
            if sh.get("phase") in ("v0.1", "v0.2"):
                sheets[sh["sheet"]] = sh
    index = {n: {row["id"]: i for i, row in enumerate(s["rows"])} for n, s in sheets.items()}
    L = ["// GENERATED by tools/gen.py from sheets/*.json. Do not edit: change the sheet and regenerate.",
         "// Remnant II cells hold only where to find the content in the player's own install.",
         "#pragma once", "#include <cstdint>", "", "namespace sheets {", "",
         "struct R2Text { const char* asset; const char* key; };",
         "struct R2Name { const char* asset; const char* pattern; };", ""]
    for name, sh in sheets.items():
        cols = sh["columns"]
        # enums
        for col, typ in cols.items():
            if typ.startswith("enum:"):
                vals = typ[5:].split("|")
                L.append(f"enum {name.capitalize()}_{col} : int {{ " +
                         ", ".join(f"{ident(name)}_{ident(col)}_{ident(v)} = {i}" for i, v in enumerate(vals)) + " };")
        L.append(f"struct {name.capitalize()} {{")
        fields = []
        for col, typ in cols.items():
            if typ == "id" or typ.startswith("str") or typ == "list" or typ.startswith("list:") \
                    or typ.startswith("effects") or typ == "recipe":
                ctype = "const char*"
            elif "num" in typ.split("|"):
                ctype = "float"
            elif typ.startswith("enum:"):
                ctype = "int"
            elif typ.startswith("ref:"):
                ctype = "int"  # row index, -1 = none
            elif typ.startswith("refasset:"):
                ctype = "const char*"  # source row resolves to its asset path
            elif typ.startswith("r2text"):
                ctype = "R2Text"
            elif typ.startswith("r2name"):
                ctype = "R2Name"
            elif typ.startswith("r2tex") or typ.startswith("r2snd"):
                ctype = "const char*"  # asset path, nullptr = none
            else:
                raise SystemExit(f"{name}.{col}: unknown column type {typ}")
            fields.append((col, typ, ctype))
            L.append(f"    {ctype} {col};")
        L.append("};")
        L.append(f"constexpr int k{name.capitalize()}Count = {len(sh['rows'])};")
        for i, row in enumerate(sh["rows"]):
            L.append(f"constexpr int {ident(name)}_{ident(row['id'])} = {i};")
        L.append(f"inline constexpr {name.capitalize()} k{name.capitalize()}[] = {{")
        for row in sh["rows"]:
            vals = []
            for col, typ, ctype in fields:
                v = row[col]
                if ctype == "float":
                    vals.append("0.0f" if v == "none" else f"{float(v)}f")  # 0 = no verified frame count
                elif typ.startswith("enum:"):
                    vals.append(f"{ident(name)}_{ident(col)}_{ident(v)}")
                elif typ.startswith("ref:"):
                    target = typ[4:].split("|")[0]
                    vals.append(str(index[target][v]) if v in index[target] else "-1")
                elif typ.startswith("refasset:"):
                    target = typ[len("refasset:"):].split("|")[0]
                    if v == "none":
                        vals.append(cstr("none"))
                    elif v in index.get(target, {}):
                        vals.append(cstr(sheets[target]["rows"][index[target][v]]["asset"]))
                    else:
                        raise SystemExit(f"{name}.{col}: unresolved animation asset reference {v!r}")
                elif ctype == "R2Text":
                    if not isinstance(v, dict):
                        vals.append("{nullptr, nullptr}")
                        continue
                    t = v["r2text"]
                    vals.append(f"{{{cstr(t['asset'])}, {cstr(t['key'])}}}")
                elif ctype == "R2Name":
                    t = v["r2name"]
                    vals.append(f"{{{cstr(t['asset'])}, {cstr(t.get('pattern', '^(' + t.get('name', '') + ')$'))}}}")
                elif typ.startswith("r2tex"):
                    vals.append(cstr(v["r2tex"]) if isinstance(v, dict) else "nullptr")
                elif typ.startswith("r2snd"):
                    vals.append("nullptr" if v == "none" else cstr(v))
                elif isinstance(v, list):
                    vals.append(cstr(",".join(x for x in v if x != "none")))
                elif typ.startswith("effects") and v == "none":
                    vals.append('""')
                else:
                    vals.append(cstr(v))
            L.append("    {" + ", ".join(vals) + "},")
        L.append("};")
        L.append(f"inline int {name}_index(const char* id) {{ for (int i = 0; i < k{name.capitalize()}Count; i++) "
                 f"{{ const char* a = k{name.capitalize()}[i].id; const char* b = id; while (*a && *a == *b) {{ a++; b++; }} "
                 f"if (*a == *b) return i; }} return -1; }}")
        if name == "hooks":
            for row in sh["rows"]:
                if re.fullmatch(r"0x[0-9A-Fa-f]+|\d+", str(row["value"])):
                    L.append(f"constexpr uintptr_t HOOKV_{ident(row['id'])} = {row['value']};")
        L.append("")
    L.append("}  // namespace sheets")
    os.makedirs(os.path.dirname(out), exist_ok=True)
    open(out, "w", encoding="utf-8", newline="\n").write("\n".join(L) + "\n")
    print("generated", out, "from", ", ".join(f"{n} ({len(s['rows'])})" for n, s in sheets.items()))


if __name__ == "__main__":
    main()
