#!/usr/bin/env python3
"""Prepare the one-file Windows installer (src/installer/setup.cpp): every file of the release as a resource.

Writes build/installer/{payload.h, setup.rc, setup.manifest, setup.ico}; `make installer` then compiles
out/RemnantHuntSetup-<version>.exe. The files are exactly the release zip's (tools/package.py), checked the same way
for game data, so the installer carries no file of either game.
usage: make_installer.py <version>
"""
import os, sys, zipfile

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import package  # noqa: E402

ROOT = package.ROOT
OUT = os.path.join(ROOT, "build", "installer")
FONTS = {"kFontTitle": "EBGaramond-Bold.ttf", "kFontBody": "Montserrat-Medium.ttf", "kFontBold": "Montserrat-Bold.ttf"}


def icon(path):
    """A worldstone: a red crystal framed in gold, on the installer's dark ground."""
    try:
        from PIL import Image, ImageDraw
    except ImportError:
        return False
    n = 256
    im = Image.new("RGBA", (n, n), (0, 0, 0, 0))
    d = ImageDraw.Draw(im)
    d.rounded_rectangle([8, 8, n - 8, n - 8], radius=48, fill=(20, 18, 16, 255), outline=(200, 162, 90, 255), width=10)
    gem = [(n / 2, 38), (n - 62, n / 2), (n / 2, n - 38), (62, n / 2)]
    d.polygon(gem, fill=(180, 40, 28, 255), outline=(200, 162, 90, 255), width=10)
    d.polygon([(n / 2, 38), (n - 62, n / 2), (n / 2, n / 2)], fill=(214, 70, 48, 255))
    im.save(path, sizes=[(16, 16), (24, 24), (32, 32), (48, 48), (64, 64), (128, 128), (256, 256)])
    return True


def c_wide(s):
    return 'L"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def rc_path(p):
    return '"' + os.path.abspath(p).replace("\\", "/") + '"'


def main():
    version = sys.argv[1]
    os.makedirs(OUT, exist_ok=True)
    entries = list(package.files())
    for src, arc in entries:
        if os.path.splitext(arc)[1].lower() in package.BANNED_EXT:
            sys.exit(f"refusing to embed game data: {arc}")
        if arc.endswith(".zip"):
            with zipfile.ZipFile(src) as inner:
                bad = [n for n in inner.namelist() if os.path.splitext(n)[1].lower() in package.BANNED_EXT]
            if bad:
                sys.exit(f"refusing to embed game data inside {arc}: {bad[:5]}")
    ids = {}
    rc = ["#include <windows.h>", ""]
    has_icon = icon(os.path.join(OUT, "setup.ico"))
    if has_icon:
        rc.append("1 ICON " + rc_path(os.path.join(OUT, "setup.ico")))
    rc.append("1 24 " + rc_path(os.path.join(OUT, "setup.manifest")))  # RT_MANIFEST
    h = ["// Generated by tools/make_installer.py. Do not edit.", "#pragma once", "",
         "struct PayloadFile { int id; const wchar_t* path; };", "",
         f'static const wchar_t kVersion[] = L"{version}";', f'static const char kVersionA[] = "{version}";', "",
         "static const PayloadFile kPayload[] = {"]
    total = 0
    for i, (src, arc) in enumerate(entries):
        rid = 1000 + i
        ids[arc] = rid
        rc.append(f"{rid} RCDATA {rc_path(src)}")
        h.append(f"    {{{rid}, {c_wide(arc.replace('/', chr(92)))}}},")
        total += os.path.getsize(src)
    h += ["};", f"static const int kPayloadCount = {len(entries)};", ""]
    for name, f in FONTS.items():
        h.append(f"static const int {name} = {ids.get('remnant_hunt/fonts/' + f, 0)};")
    nums = ",".join((version.split(".") + ["0", "0", "0", "0"])[:4])
    rc += ["", "1 VERSIONINFO", f"FILEVERSION {nums}", f"PRODUCTVERSION {nums}", "BEGIN",
           ' BLOCK "StringFileInfo"', " BEGIN", '  BLOCK "040904B0"', "  BEGIN",
           '   VALUE "FileDescription", "Remnant Hunt Setup"', '   VALUE "ProductName", "Remnant Hunt"',
           f'   VALUE "ProductVersion", "{version}"', f'   VALUE "FileVersion", "{version}"',
           '   VALUE "LegalCopyright", "GPL-3.0-or-later"', '   VALUE "OriginalFilename", "RemnantHuntSetup.exe"',
           "  END", " END", ' BLOCK "VarFileInfo"', " BEGIN", '  VALUE "Translation", 0x409, 1200', " END", "END"]
    open(os.path.join(OUT, "setup.rc"), "w", newline="\n").write("\n".join(rc) + "\n")
    open(os.path.join(OUT, "payload.h"), "w", newline="\n").write("\n".join(h) + "\n")
    open(os.path.join(OUT, "setup.manifest"), "w", newline="\n").write(f"""<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<assembly xmlns="urn:schemas-microsoft-com:asm.v1" manifestVersion="1.0">
  <assemblyIdentity version="{nums.replace(',', '.')}" name="RemnantHunt.Setup" type="win32"/>
  <description>Remnant Hunt Setup</description>
  <dependency><dependentAssembly>
    <assemblyIdentity type="win32" name="Microsoft.Windows.Common-Controls" version="6.0.0.0"
      processorArchitecture="*" publicKeyToken="6595b64144ccf1df" language="*"/>
  </dependentAssembly></dependency>
  <trustInfo xmlns="urn:schemas-microsoft-com:asm.v3"><security><requestedPrivileges>
    <requestedExecutionLevel level="asInvoker" uiAccess="false"/>
  </requestedPrivileges></security></trustInfo>
  <compatibility xmlns="urn:schemas-microsoft-com:compatibility.v1"><application>
    <supportedOS Id="{{8e0f7a12-bfb3-4fe8-b9a5-48fd50a15a9a}}"/>
  </application></compatibility>
  <application xmlns="urn:schemas-microsoft-com:asm.v3"><windowsSettings>
    <dpiAware xmlns="http://schemas.microsoft.com/SMI/2005/WindowsSettings">true</dpiAware>
  </windowsSettings></application>
</assembly>
""")
    print(f"installer payload: {len(entries)} files, {total:,} bytes, icon {'yes' if has_icon else 'no'}")


if __name__ == "__main__":
    main()
